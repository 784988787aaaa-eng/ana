/**
 * =====================================================================
 * ملف: حالات الحوارات المنبثقة لإعدادات العملات (CurrencyDialogState.kt)
 * =====================================================================
 * 
 * [الغرض العام والتعليمي من الملف]:
 * يمثل هذا الملف واجهة محكمة النمط (Sealed Interface) لتمثيل وتدفق حالات
 * الحوارات التفاعلية المنبثقة في شاشة إعدادات وأسعار صرف العملات.
 * 
 * [المسؤوليات المعمارية والتقنية للملف]:
 * 1. نمذجة الحالة المعمارية الآمنة (Type-Safe State Modeling):
 *    - حصر الحالات الممكنة لمنع التضارب بين النوافذ المنبثقة المنفذة لعمليات التقييم وإعادة الحساب.
 * 2. دعم حالة الاستقرار والخمول (None Idle State):
 *    - تمثيل حالة عدم وجود أي حوار مفتوح كحالة ابتدائية صريحة.
 * 3. تمرير بيانات إعادة التقييم (Revaluation Confirmation Payload):
 *    - تغليف العملة المستهدفة وسعر الصرف الجديد [BigDecimal] لتأكيد إعادة التقييم المالي الشامل للحسابات.
 */
package com.smartledger.aldaftar.ui.components

// ---------------------------------------------------------------------
// استيراد الحسابات الرياضية الدقيقة للعملات
// ---------------------------------------------------------------------
import java.math.BigDecimal

/**
 * [واجهة حالات حوار العملات - CurrencyDialogState]:
 * تعبر عن الحوارات الفرعية المفتوحة فوق نافذة إعدادات العملة.
 */
sealed interface CurrencyDialogState {

    /**
     * [حالة الخمول - None]:
     * تدل على عدم وجود أي حوار تأكيدي مفتوح في الوقت الحالي.
     */
    object None : CurrencyDialogState

    /**
     * [حوار تأكيد إعادة تقييم المعاملات التاريخية - RevalueConfirm]:
     * يُعرض عندما يغير المستخدم سعر صرف عملة أجنبية ليسأله عما إذا كان يرغب في تحديث المعاملات السابقة.
     * 
     * @property targetCurrency رمز العملة المستهدفة (مثل دولار، يورو).
     * @property newRate سعر الصرف الجديد المراد تطبيقه بدقة [BigDecimal].
     */
    data class RevalueConfirm(
        val targetCurrency: String,
        val newRate: BigDecimal = BigDecimal.ZERO
    ) : CurrencyDialogState
}

