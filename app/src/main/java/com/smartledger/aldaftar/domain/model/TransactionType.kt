/**
 * =====================================================================
 * ملف: نوع المعاملة المالية والتجارية (.)
 * =====================================================================
 * 
 * [الغرض العام والتعليمي من الملف]:
 * يمثل هذا التعداد ( ) التصنيف المعياري لكافة أنواع الحركات المالية
 * والقيود المحاسبية في التطبيق (الديون، الدفعات، الإيرادات، والمصروفات).
 * يوفر قيمة نصية متوافقة مع قاعدة البيانات المحلية ودالة تحليل آمنة وسريعة.
 * 
 * [المسؤوليات المعمارية والتقنية للملف]:
 * 1. حصر أنواع القيود المحاسبية (  ):
 *    - حركات الديون والالتزامات للعملاء والموردين (له، عليه، تسديد منه، تسديد له).
 *    - حركات الدخل العام والمصاريف التشغيلية (إيراد، مصروف).
 * 2. البحث والتحويل السريع ((1)   ):
 *    - استخدام خارطة تجميعية [_] للبحث الفوري عن النوع عبر القيمة النصية.
 * 3. الأمان ضد القيم المعدومة والخاطئة (- ):
 *    - الإرجاع التلقائي للنوع الافتراضي [__] عند تمرير قيم غير معروفة أو معدومة.
 */
package com.smartledger.aldaftar.domain.model

/**
 * [تعداد نوع المعاملة المالية - ]:
 * @  القيمة النصية المخزنة في قاعدة البيانات.
 */
enum class TransactionType(val value: String) {
    /** حركة دين على العميل (لنا عليه / مدين) */
    OWED_BY_THEM("OWED_BY_THEM"),

    /** حركة التزام للعميل (له علينا / دائن) */
    OWED_TO_THEM("OWED_TO_THEM"),

    /** دفعة مسددة من العميل لحسابه (تسديد منه) */
    PAYMENT_BY_THEM("PAYMENT_BY_THEM"),

    /** دفعة مسددة للعميل من حسابنا (دفعة له) */
    PAYMENT_TO_THEM("PAYMENT_TO_THEM"),

    /** حركة إيراد / دخل مالي عام للمحل */
    INCOME("INCOME"),

    /** حركة مصروف / نفقات تشغيلية عامة */
    EXPENSE("EXPENSE");

    /**
     * الكائن المرافق المساعد لعمليات التحويل والبحث المعجمي.
     */
    companion object {
        /** خارطة ربط القيم النصية بكائنات التعداد للبحث الفوري */
        private val VALUE_MAP = entries.associateBy { it.value }

        /**
         * [استخراج نوع المعاملة من القيمة النصية - ]:
         * يطابق النص بنوع المعاملة المقابل مع توفير قيمة افتراضية آمنة.
         *
         * @  النص المخزن في قاعدة البيانات.
         * @ كائن [] المقابل.
         */
        fun fromValue(value: String?): TransactionType {
            if (value == null) return OWED_BY_THEM
            return VALUE_MAP[value] ?: OWED_BY_THEM
        }
    }
}


