package com.smartledger.aldaftar.data.serialization.pdf

/**
 * [تعداد إجراءات مستندات الـ PDF - PdfAction]:
 * يحدد نوع العملية المطلوبة على الملف المولد.
 */
enum class PdfAction {
    /** مشاركة عامة عبر قائمة تطبيقات النظام */
    SHARE,
    /** فتح الملف ومعاينته فورياً عبر عارض PDF */
    VIEW,
    /** حفظ الملف في مجلد التنزيلات/المستندات بالهاتف */
    SAVE_LOCAL,
    /** إرسال الملف مباشرة إلى محادثة واتساب */
    WHATSAPP_DIRECT;

    companion object {
        /**
         * [تحويل النص إلى إجراء PDF - from]:
         * يطابق النص غير الحساس لحالة الأحرف مع عناصر التعداد، ويعيد [SHARE] كقيمة افتراضية.
         *
         * @param action اسم الإجراء كنص.
         * @return كائن [PdfAction] المقابل.
         */
        fun from(action: String): PdfAction {
            return values().find { it.name.equals(action, ignoreCase = true) } ?: SHARE
        }
    }
}

