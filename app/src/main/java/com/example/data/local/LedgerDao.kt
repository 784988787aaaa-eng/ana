 * ملف: كائن الوصول المجمع لبيانات دفتر اليومية (LedgerDao.kt)
 * =====================================================================
 * 
 * [الغرض العام والتعليمي من الملف]:
 * يمثل هذا الملف واجهة مجمعة (Composite DAO) تدمج عمليات دفتر اليومية
 * [TransactionDao] وعمليات التصنيفات المخصصة [CustomCategoryDao] في واجهة موحدة.
 * 
 * [النمط المعماري - Aggregated Interface Pattern]:
 * 1. فصل الاهتمامات (Separation of Concerns): تم تقسيم العمليات برمجياً إلى واجهتين متخصصتين:
 *    - `TransactionDao`: لحركات الدخل والمصروف والفلترة الزمنية.
 *    - `CustomCategoryDao`: لإدارة التصنيفات المخصصة وترتيبها.
 * 2. التجميع والتوافق العكسي: ترث واجهة `LedgerDao` كلاً من الواجهتين معاً، مما يتيح لمستودعات
 *    البيانات (Repositories) القديمة والجديدة الوصول لكافة عمليات دفتر اليومية دون تكرار للأكواد.
 * 3. توليد كود Room الذكي: تقوم مكتبة Room في وقت التجميع (Compile-time) بتوليد كلاس تنفيذي واحد
 *    يدمج كافة استعلامات الواجهتين بكفاءة متناهية.
 */
