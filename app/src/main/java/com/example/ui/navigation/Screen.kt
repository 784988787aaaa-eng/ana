package com.example.ui.navigation

/*
 * =====================================================================================
 * حزمة إدارة وجهات التنقل (Application Navigation Package)
 * -------------------------------------------------------------------------------------
 * تحتوي هذه الفئة على تعداد وجهات الشاشات الرئيسية للتطبيق (Navigation Destinations)،
 * والتي تستخدم للتنقل الآمن بين الشاشات والتحكم في مكدس التوجيه (Compose Navigation Backstack).
 * =====================================================================================
 */

/*
 * =====================================================================================
 * تعداد شاشات ووجهات التطبيق (Screen Navigation Enum)
 * -------------------------------------------------------------------------------------
 * [الوصف والهدف]:
 * تعداد نمطي آمن يحدد كافة الوجهات المعتمدة في مكدس التنقل الداخلي للتطبيق.
 * =====================================================================================
 */
enum class Screen {
    // شاشة الحبايب: إدارة دليل العملاء والديون والأرصدة المشتركة
    HABAYEB,

    // شاشة دفتر اليومية: سجل المعاملات النقدية اليومية والمقبوضات والمصروفات
    LEDGER,

    // شاشة الإعدادات: تفضيلات العملة، النسخ الاحتياطي، والخيارات العامة
    SETTINGS,

    // شاشة سلة المهملات: استعادة أو حذف المعاملات والحسابات المحذوفة مؤقتاً
    TRASH,

    // شاشة الملف التجاري: إدارة شعار واسم ورأسية فواتير المنشأة التجارية
    BUSINESS_PROFILE,

    // شاشة الأمان والحماية: إعداد القفل البيومتري، رمز PIN، وإدارة الترخيص
    SECURITY
}

