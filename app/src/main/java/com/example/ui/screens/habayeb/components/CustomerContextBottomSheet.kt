                            ContextMenuItem(
                                icon = Icons.Default.Check,
                                text = stringResource(R.string.context_menu_multi_select),
                                iconTint = activeThemeColor,
                                iconBgColor = activeThemeColor.copy(alpha = 0.1f),
                                onClick = {
                                    onEnableMultiSelect()
                                    onDismiss()
                                }
                            )
                        }

