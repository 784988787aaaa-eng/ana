@Composable
fun HabayebHeaderTopBar(
    isSearchActive: Boolean,
    onSearchActiveChanged: (Boolean) -> Unit,
    searchQuery: String,
    onSearchQueryChanged: (String) -> Unit,
    onMenuClick: () -> Unit,
    haptic: HapticFeedback,
    netDebt: BigDecimal,
    isPrivacyMode: Boolean,
    onTogglePrivacy: () -> Unit,
    currencySymbol: String,
    onHeaderDoubleClick: () -> Unit = {},
    isFloatingActive: Boolean = false,
    onToggleFloatingClick: () -> Unit = {},
    modifier: Modifier = Modifier
) {
    Column(
        modifier = modifier
            .fillMaxWidth()
            .statusBarsPadding()
            .padding(bottom = 8.dp)
    ) {
        if (isSearchActive) {
            HabayebSearchHeaderBar(
                searchQuery = searchQuery,
                onSearchQueryChanged = onSearchQueryChanged,
                onCloseSearch = {
                    onSearchQueryChanged("")
                    onSearchActiveChanged(false)
                },
                haptic = haptic
            )
        } else {
            HabayebNormalHeaderBar(
                netDebt = netDebt,
                isPrivacyMode = isPrivacyMode,
                currencySymbol = currencySymbol,
                isFloatingActive = isFloatingActive,
                onMenuClick = onMenuClick,
                onOpenSearch = { onSearchActiveChanged(true) },
                onTogglePrivacy = onTogglePrivacy,
                onHeaderDoubleClick = onHeaderDoubleClick,
                onToggleFloatingClick = onToggleFloatingClick,
                haptic = haptic
            )
        }
    }
}

@Composable
private fun HabayebSearchHeaderBar(
    searchQuery: String,
    onSearchQueryChanged: (String) -> Unit,
    onCloseSearch: () -> Unit,
    haptic: HapticFeedback
) {
    val focusRequester = remember { FocusRequester() }

    Row(
        modifier = Modifier
            .fillMaxWidth()
            .padding(horizontal = 16.dp, vertical = 6.dp)
            .height(46.dp)
            .background(MaterialTheme.colorScheme.onPrimary.copy(alpha = 0.18f), RoundedCornerShape(23.dp))
            .padding(horizontal = 12.dp),
        horizontalArrangement = Arrangement.SpaceBetween,
        verticalAlignment = Alignment.CenterVertically
    ) {
        // Close Search Icon Button
        IconButton(
            onClick = {
                haptic.performHapticFeedback(HapticFeedbackType.TextHandleMove)
                onCloseSearch()
            },
            modifier = Modifier.size(32.dp)
        ) {
            Icon(
                imageVector = Icons.Default.Close,
                contentDescription = stringResource(id = R.string.habayeb_close_search),
                tint = MaterialTheme.colorScheme.onPrimary,
                modifier = Modifier.size(18.dp)
            )
        }

        // Search Input field in center
        BasicTextField(
            value = searchQuery,
            onValueChange = onSearchQueryChanged,
            textStyle = TextStyle(
                color = MaterialTheme.colorScheme.onPrimary,
                fontSize = 15.sp,
                fontWeight = FontWeight.SemiBold,
                textAlign = TextAlign.Right
            ),
            cursorBrush = SolidColor(MaterialTheme.colorScheme.onPrimary),
            modifier = Modifier
                .weight(1f)
                .padding(horizontal = 12.dp)
                .focusRequester(focusRequester),
            decorationBox = { innerTextField ->
                Box(
                    modifier = Modifier.fillMaxWidth(),
                    contentAlignment = Alignment.CenterStart
                ) {
                    if (searchQuery.isEmpty()) {
                        Text(
                            text = stringResource(id = R.string.habayeb_search_hint),
                            color = MaterialTheme.colorScheme.onPrimary.copy(alpha = 0.65f),
                            fontSize = 14.sp,
                            fontWeight = FontWeight.Normal,
                            textAlign = TextAlign.Right,
                            modifier = Modifier.fillMaxWidth()
                        )
                    }
                    innerTextField()
                }
            }
        )

        // Passive Search Icon
        Icon(
            imageVector = Icons.Default.Search,
            contentDescription = null,
            tint = MaterialTheme.colorScheme.onPrimary.copy(alpha = 0.8f),
            modifier = Modifier.size(20.dp)
        )
    }

    val keyboardController = LocalSoftwareKeyboardController.current
    LaunchedEffect(Unit) {
        try {
            awaitFrame()
            focusRequester.requestFocus()
            keyboardController?.show()
        } catch (e: Exception) {
            e.printStackTrace()
        }
    }
}

