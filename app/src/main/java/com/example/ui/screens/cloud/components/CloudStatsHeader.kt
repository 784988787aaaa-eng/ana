@Composable
fun CloudStatsHeader(
    email: String,
    backupsCount: Int,
    isFetching: Boolean,
    onRefresh: () -> Unit,
    isSelectionMode: Boolean = false,
    isAllSelected: Boolean = false,
    onToggleSelectAll: () -> Unit = {}
) {
    Card(
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.2f)),
        border = BorderStroke(0.5.dp, MaterialTheme.colorScheme.outlineVariant.copy(alpha = 0.5f)),
        shape = RoundedCornerShape(12.dp),
        modifier = Modifier.fillMaxWidth()
    ) {
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(horizontal = 10.dp, vertical = 6.dp),
            horizontalArrangement = Arrangement.SpaceBetween,
            verticalAlignment = Alignment.CenterVertically
        ) {
            // Right Section: Icon + Email + Stats Summary
            Row(
                horizontalArrangement = Arrangement.spacedBy(6.dp),
                verticalAlignment = Alignment.CenterVertically,
                modifier = Modifier.weight(1f, fill = false)
            ) {
                Box(
                    modifier = Modifier
                        .size(26.dp)
                        .clip(CircleShape)
                        .background(if (isSelectionMode) MaterialTheme.mizanColors.infoContainer else MaterialTheme.mizanColors.creditContainer),
                    contentAlignment = Alignment.Center
                ) {
                    Icon(
                        imageVector = if (isSelectionMode) Icons.Default.Checklist else Icons.Default.Backup,
                        contentDescription = null,
                        tint = if (isSelectionMode) MaterialTheme.mizanColors.info else MaterialTheme.mizanColors.credit,
                        modifier = Modifier.size(14.dp)
                    )
                }

                Column(
                    verticalArrangement = Arrangement.Center,
                    horizontalAlignment = Alignment.Start
                ) {
                    Row(
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.spacedBy(4.dp)
                    ) {
                        Text(
                            text = email,
                            color = MaterialTheme.colorScheme.onSurface,
                            fontWeight = FontWeight.Bold,
                            fontSize = 11.sp,
                            maxLines = 1
                        )
                        Box(
                            modifier = Modifier
                                .size(6.dp)
                                .clip(CircleShape)
                                .background(MaterialTheme.mizanColors.credit)
                        )
                    }
                    /**
                     * نص إحصاءات السحابة يعتمد بالكامل على الموارد النصية لضمان قابلية الترجمة والتوحيد المعماري.
                     */
                    Text(
                        text = stringResource(R.string.cloud_stat_count_pattern, backupsCount) +
                                stringResource(R.string.cloud_stat_divider) +
                                stringResource(R.string.cloud_stat_taken_space),
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        fontSize = 9.sp
                    )
                }
            }

            // Left Section: Actions
            Row(
                horizontalArrangement = Arrangement.spacedBy(4.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                if (isSelectionMode) {
                    TextButton(
                        onClick = onToggleSelectAll,
                        colors = ButtonDefaults.textButtonColors(contentColor = MaterialTheme.mizanColors.info),
                        contentPadding = PaddingValues(horizontal = 6.dp, vertical = 0.dp),
                        modifier = Modifier.height(26.dp)
                    ) {
                        Text(
                            text = if (isAllSelected) stringResource(R.string.cloud_btn_cancel_selection) else stringResource(R.string.cloud_btn_select_all),
                            fontSize = 11.sp,
                            fontWeight = FontWeight.Bold
                        )
                    }
                } else {
                    IconButton(
                        onClick = onRefresh,
                        enabled = !isFetching,
                        modifier = Modifier
                            .size(28.dp)
                            .testTag("refresh_cloud_backups_stats_button")
                    ) {
                        Icon(
                            imageVector = Icons.Default.Refresh,
                            contentDescription = stringResource(R.string.cloud_desc_refresh),
                            tint = if (isFetching) MaterialTheme.mizanColors.contentTertiary else MaterialTheme.colorScheme.primary,
                            modifier = Modifier.size(15.dp)
                        )
                    }
                }
            }
        }
    }
}

