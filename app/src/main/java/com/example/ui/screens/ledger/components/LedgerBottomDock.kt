@Composable
fun LedgerBottomDock(
    isSelectionMode: Boolean,
    selectedTxIdsCount: Int,
    onDeleteSelectedClick: () -> Unit,
    onShowCommitmentsClick: () -> Unit,
    onAddIncomeClick: () -> Unit,
    onAddExpenseClick: () -> Unit,
    modifier: Modifier = Modifier
) {
    val haptic = LocalHapticFeedback.current

    Column(
        modifier = modifier
            .padding(bottom = 0.dp) // Removed extra bottom padding as it's passed from caller
            .fillMaxWidth(),
        verticalArrangement = Arrangement.spacedBy(8.dp),
        horizontalAlignment = Alignment.CenterHorizontally
    ) {
        if (!isSelectionMode) {
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .height(42.dp)
                    .padding(horizontal = 16.dp),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.spacedBy(12.dp)
            ) {
                val mizanColors = MaterialTheme.mizanColors
                val incomeBg = mizanColors.credit
                val expenseBg = mizanColors.debt

                // Add Income Button (First element - Right side in RTL)
                Button(
                    onClick = {
                        haptic.performHapticFeedback(HapticFeedbackType.LongPress)
                        onAddIncomeClick()
                    },
                    colors = ButtonDefaults.buttonColors(containerColor = incomeBg), // Secondary Mint/Green
                    shape = RoundedCornerShape(16.dp),
                    contentPadding = PaddingValues(0.dp),
                    modifier = Modifier
                        .weight(1f)
                        .height(42.dp)
                ) {
                    Icon(Icons.Default.Add, contentDescription = stringResource(id = R.string.ledger_add_income), tint = mizanColors.onCredit, modifier = Modifier.size(16.dp))
                    Spacer(modifier = Modifier.width(4.dp))
                    Text(stringResource(id = R.string.ledger_add_income), color = mizanColors.onCredit, fontWeight = FontWeight.Bold, fontSize = 12.sp)
                }

                // Center Target Button (Goals/Commitments)
                Box(
                    modifier = Modifier
                        .size(42.dp)
                        .clip(CircleShape)
                        .background(MaterialTheme.colorScheme.surfaceVariant)
                        .border(1.dp, MaterialTheme.colorScheme.outlineVariant, CircleShape)
                        .clickable {
                            haptic.performHapticFeedback(HapticFeedbackType.LongPress)
                            onShowCommitmentsClick()
                        },
                    contentAlignment = Alignment.Center
                ) {
                    Text(
                        text = "🎯",
                        fontSize = 18.sp
                    )
                }

                // Add Expense Button (Third element - Left side in RTL)
                Button(
                    onClick = {
                        haptic.performHapticFeedback(HapticFeedbackType.LongPress)
                        onAddExpenseClick()
                    },
                    colors = ButtonDefaults.buttonColors(containerColor = expenseBg), // Destructive Crimson/Soft Red
