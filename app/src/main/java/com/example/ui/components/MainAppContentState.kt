package com.example.ui.components

/*
 * =====================================================================================
 * حزمة إدارة حالة المحتوى الرئيسي (Main App Content State Management)
 * -------------------------------------------------------------------------------------
 * تحتوي هذه الفئة على كائنات إدارة الحالة (State Holders) التي تفصل منطق التحكم
 * في القائمة الجانبية (Navigation Drawer) عن عناصر الرسم المرئي في واجهة المستخدم.
 * =====================================================================================
 */

import androidx.compose.runtime.Composable
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.remember
import androidx.compose.runtime.setValue

/*
 * =====================================================================================
 * كلاس إدارة حالة القائمة الجانبية والمحتوى (MainAppContentState)
 * -------------------------------------------------------------------------------------
 * [الوصف والهدف]:
 * كائن تخزين حالة منفصل يدير تفاعلات القائمة الجانبية:
 * 1. متابعة حالة فتح أو إغلاق القائمة الجانبية (isDrawerOpen).
 * 2. توفير دوال تحكم صريحة (openDrawer, closeDrawer, toggleDrawer).
 * 3. استدعاء ردود أفعال النقر على زر القائمة (onMenuClickAction).
 *
 * [المُدخلات]:
 * - initialIsDrawerOpen: الحالة المبدئية لفتح القائمة.
 * - onMenuClickAction: الإجراء المخصص المنفذ عند النقر على زر القائمة.
 * =====================================================================================
 */
class MainAppContentState(
    initialIsDrawerOpen: Boolean = false,
    private val onMenuClickAction: (() -> Unit)? = null
) {
    /*
     * متغير الحالة التفاعلي لفتح أو إغلاق القائمة الجانبية
     */
    var isDrawerOpen by mutableStateOf(initialIsDrawerOpen)

    /*
     * ---------------------------------------------------------------------------------
     * دالة معالجة النقر على أيقونة القائمة (handleMenuClick)
     * ---------------------------------------------------------------------------------
     * تنفذ الإجراء المخصص لتوسيع أو طي القائمة الجانبية المعرف من قبل المكون الأب.
     * ---------------------------------------------------------------------------------
     */
    fun handleMenuClick() {
        onMenuClickAction?.invoke()
    }

    /*
     * ---------------------------------------------------------------------------------
     * دالة فتح القائمة الجانبية (openDrawer)
     * ---------------------------------------------------------------------------------
     */
    fun openDrawer() {
        isDrawerOpen = true
        onMenuClickAction?.invoke()
    }

    /*
     * ---------------------------------------------------------------------------------
     * دالة إغلاق القائمة الجانبية (closeDrawer)
     * ---------------------------------------------------------------------------------
     */
    fun closeDrawer() {
        isDrawerOpen = false
    }

    /*
     * ---------------------------------------------------------------------------------
     * دالة تبديل حالة القائمة الجانبية (toggleDrawer)
     * ---------------------------------------------------------------------------------
     * تفتح القائمة إن كانت مغلقة، وتغلقها إن كانت مفتوحة.
     * ---------------------------------------------------------------------------------
     */
    fun toggleDrawer() {
        if (isDrawerOpen) {
            closeDrawer()
        } else {
            openDrawer()
        }
    }

    /*
     * ---------------------------------------------------------------------------------
     * دالة تحديث الحالة من مصدر خارجي (updateDrawerState)
     * ---------------------------------------------------------------------------------
     */
    fun updateDrawerState(isOpen: Boolean) {
        isDrawerOpen = isOpen
    }
}

/*
 * =====================================================================================
 * دالة مساعدة لتذكر وإنشاء كائن الحالة (rememberMainAppContentState)
 * -------------------------------------------------------------------------------------
 * [الوصف والهدف]:
 * دالة Composable تقوم بإنشاء وتذكر نسخة من MainAppContentState طوال دورة حياة الواجهة،
 * مع مزامنة حالة القائمة الخارجية الممررة عند حدوث أي إعادة تكوين (Recomposition).
 * =====================================================================================
 */
@Composable
fun rememberMainAppContentState(
    isDrawerOpen: Boolean = false,
    onMenuClick: (() -> Unit)? = null
): MainAppContentState {
    val state = remember(isDrawerOpen, onMenuClick) {
        MainAppContentState(initialIsDrawerOpen = isDrawerOpen, onMenuClickAction = onMenuClick)
    }
    state.updateDrawerState(isDrawerOpen)
    return state
}

